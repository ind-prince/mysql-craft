import type { PoolOptions, ResultSetHeader, RowDataPacket } from 'mysql2/promise';

/**
 * Configuration options for the Database client.
 */
export interface DatabaseConfig extends PoolOptions {
  /**
   * Enable beautiful terminal query logging.
   * Default: false
   */
  debug?: boolean | LoggerConfig;

  /**
   * Slow query threshold in milliseconds. Queries exceeding this will be logged as warnings.
   * Default: 500ms
   */
  slowQueryThresholdMs?: number;

  /**
   * Number of automatic retry attempts on transient network or connection errors.
   * Default: 3
   */
  retryAttempts?: number;

  /**
   * Backoff delay between retry attempts in milliseconds.
   * Default: 300ms
   */
  retryDelayMs?: number;

  /**
   * Field names to mask in console query logs to avoid leaking credentials.
   * Default: ['password', 'passwd', 'token', 'secret', 'credit_card', 'hash']
   */
  sensitiveKeys?: string[];
}

/**
 * Options to customize terminal logging.
 */
export interface LoggerConfig {
  /**
   * Turn query logging on/off.
   */
  enabled?: boolean;

  /**
   * Mask values for sensitive parameter keys in logs.
   * Default: true
   */
  maskSensitiveParams?: boolean;

  /**
   * Maximum length of SQL query to display in logs before truncating.
   * Default: 1000 characters
   */
  maxSqlLength?: number;

  /**
   * Custom list of parameter names to mask.
   */
  sensitiveKeys?: string[];

  /**
   * Threshold in ms to flag queries as SLOW.
   * Default: 500ms
   */
  slowThresholdMs?: number;
}

/**
 * Result returned by .insert() operations.
 */
export interface InsertResult {
  /**
   * The auto-increment ID generated by the insert statement (if applicable).
   */
  insertId: number;

  /**
   * Total number of rows affected by the insert.
   */
  affectedRows: number;
}

/**
 * Result returned by .update() operations.
 */
export interface UpdateResult {
  /**
   * Number of rows matching the WHERE criteria.
   */
  affectedRows: number;

  /**
   * Number of rows actually modified.
   */
  changedRows: number;
}

/**
 * Result returned by .delete() operations.
 */
export interface DeleteResult {
  /**
   * Number of rows removed from the table.
   */
  affectedRows: number;
}

/**
 * Pool metrics and connection health report.
 */
export interface HealthCheckResult {
  status: 'healthy' | 'unhealthy';
  latencyMs: number;
  timestamp: string;
  pool: {
    totalConnections: number;
    activeConnections: number;
    idleConnections: number;
    queuedRequests: number;
  };
  error?: string;
}

/**
 * Supported primitive types for query parameters.
 */
export type QueryParam =
  | string
  | number
  | boolean
  | Date
  | Buffer
  | null
  | undefined;

/**
 * Query value input types.
 */
export type QueryParams = QueryParam[] | Record<string, any>;

/**
 * Helper alias for standard MySQL row data.
 */
export type DatabaseRow = RowDataPacket;

/**
 * Re-export mysql2 result set header for convenience.
 */
export type { ResultSetHeader };
